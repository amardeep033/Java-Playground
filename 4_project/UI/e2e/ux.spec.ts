import {test,expect} from "./fixtures";
test("collapsible navigation, persistent context, profile overlay and bottom pagination",async({page,request},testInfo)=>{
  const api=process.env.E2E_API_URL!;
  const user=await(await request.post(`${api}/users`,{data:{name:"UX owner",email:`ux-${process.env.E2E_RUN_ID}@example.com`,password:"ExamplePass123!"}})).json();
  const apps=[];
  for(const name of ["Alpha app","Beta app"]) apps.push(await(await request.post(`${api}/users/${user.id}/applications`,{data:{name}})).json());
  const root=`/users/${user.id}`;
  await page.goto(`${root}/apps/${apps[1].id}/overview`);
  const nav=page.getByRole("navigation",{name:"Main navigation"});
  await expect(nav.getByRole("link")).toHaveText(["Overview","Incoming requests","Events","Deliveries","Dead letters","API keys","Event types","Endpoints","Users & access","Applications","Audit logs"]);
  await nav.getByRole("button",{name:"Monitoring",exact:true}).click();
  await expect(nav.getByRole("link",{name:"Events",exact:true})).toHaveCount(0);
  await expect(nav.getByRole("button",{name:"Monitoring",exact:true})).toHaveAttribute("aria-expanded","false");
  await nav.getByRole("button",{name:"Monitoring",exact:true}).click();
  await nav.getByRole("link",{name:"Applications",exact:true}).click();
  await expect(page.getByRole("button",{name:"Select application",exact:true})).toContainText("Beta app");
  await expect(nav.getByRole("link",{name:"Endpoints",exact:true})).toHaveAttribute("href",`${root}/apps/${apps[1].id}/endpoints`);
  await page.getByLabel("Search applications").fill("Alpha app");
  await expect(page.getByRole("article")).toHaveCount(1);
  await expect(page.getByRole("article").getByRole("button",{name:/Delete|Deactivate/})).toHaveCount(0);
  await expect(page.getByRole("article").locator(".app-open")).toHaveCount(0);
  await page.getByRole("button",{name:"Edit",exact:true}).click();
  await expect(page.getByRole("dialog").getByLabel("Name",{exact:true})).toHaveValue("Alpha app");
  await page.getByRole("button",{name:"Delete",exact:true}).click();
  await expect(page.locator(".danger-dialog .button-danger")).toHaveText("Confirm delete");
  await page.getByRole("button",{name:"Keep resource",exact:true}).click();
  await page.keyboard.press("Escape");
  const footer=await page.getByRole("navigation",{name:"Pagination",exact:true}).boundingBox();
  const main=await page.locator("main.page-content").boundingBox();
  expect(footer!.y+footer!.height).toBeGreaterThan(main!.y+main!.height-45);
  await page.screenshot({path:testInfo.outputPath("apps-desktop.png"),fullPage:true});
  await expect(page.getByRole("button",{name:"Profile & security",exact:true})).toHaveAttribute("title",/UX owner.*ADMIN/);
  await page.getByRole("button",{name:"Profile & security",exact:true}).click();
  await expect(page.getByRole("dialog").getByRole("heading",{name:"Profile & security",exact:true})).toBeVisible();
  await expect(page.getByRole("dialog").locator(".settings-stack > section")).toHaveCount(2);
  await expect(page.getByRole("cell",{name:"Successful",exact:true}).first()).toBeVisible();
  await expect(page).toHaveURL(new RegExp(`${root}/applications$`));
  await page.screenshot({path:testInfo.outputPath("settings-desktop.png"),fullPage:true});
  await page.getByRole("button",{name:"Close dialog",exact:true}).click();
  await page.getByRole("button",{name:"Select application",exact:true}).click();
  await page.getByRole("button",{name:"Select Alpha app",exact:true}).click();
  await page.reload();
  await expect(page.getByRole("button",{name:"Select application",exact:true})).toContainText("Alpha app");
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${root}/applications`);
  await expect(page.getByRole("heading",{name:"Alpha app",exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("apps-mobile.png"),fullPage:true});
});

