import {test,expect} from "./fixtures";
test("whole-row selection and related dropdown navigate between filtered lists",async({page,request},testInfo)=>{
 test.setTimeout(90_000);
 const api=process.env.E2E_API_URL!;const receiver=process.env.E2E_RECEIVER_URL!;
 const user=await(await request.post(`${api}/users`,{data:{name:"Tracking owner",email:`tracking-${Date.now()}@example.com`,password:"ExamplePass123!"}})).json();
 const app=await(await request.post(`${api}/users/${user.id}/applications`,{data:{name:"Tracking app"}})).json();
 await request.post(`${receiver}/control`,{data:{path:"/tracking-fail",status:503}});
 const type=await(await request.post(`${api}/applications/${app.id}/event-types`,{data:{name:"tracking.created"}})).json();
 for(const [name,path] of [["Success destination","/tracking-success"],["Failed destination","/tracking-fail"]]) await request.post(`${api}/applications/${app.id}/endpoints`,{data:{name,url:receiver+path,eventTypeIds:[type.id],configuration:{enabled:true,rateLimitPerSecond:20,concurrencyLimit:2,timeoutMs:1000,maxAttempts:1}}});
 const response=await request.post(`${api}/applications/${app.id}/events`,{headers:{"Idempotency-Key":`tracking-${Date.now()}`},data:{eventType:type.name,payload:{orderId:"tracking-order"}}});
 expect(response.status()).toBe(202);const accepted=await response.json();const requestId=response.headers()["x-request-id"];
 await expect.poll(async()=> (await(await request.get(`${api}/applications/${app.id}/events/${accepted.id}`)).json()).status).toBe("FAILED");
 const root=`/users/${user.id}/apps/${app.id}`;
 await page.goto(`${root}/incoming-requests?q=${requestId}`);
 // Clicking the result column opens the same request as clicking its ID.
 const row=page.locator("tbody tr").first();
 await row.locator("td").nth(1).click();
 const popup=page.locator(".tracking-dialog");
 await expect(popup.getByRole("heading",{name:"Incoming request",exact:true})).toBeVisible();
 expect((await popup.boundingBox())!.width).toBeGreaterThan(900);
 await expect(popup.getByRole("button",{name:"Back",exact:true})).toHaveCount(0);
 await expect(popup.getByLabel("Tracking stages")).toHaveCount(0);
 async function related(label:string){if(label!=="View in events")await popup.getByText("Related records",{exact:true}).click();await popup.getByRole("button",{name:label,exact:true}).click();await expect(popup).toHaveCount(0);}
 await related("View in events");
 await expect(page).toHaveURL(new RegExp(`/events\\?q=${accepted.id}`));
 await expect(page.locator("tr.selected-row")).toHaveCount(1);
 await page.locator("tbody tr td").nth(2).click();
 await expect(popup.getByText("tracking-order",{exact:false})).toBeVisible();
 await expect(popup.locator("table")).toHaveCount(0);
 await related("View in deliveries");
 await expect(page).toHaveURL(new RegExp(`/deliveries\\?eventId=${accepted.id}`));
 await expect(page.locator("tbody tr")).toHaveCount(2);
 await page.getByRole("row").filter({hasText:"503"}).locator("td").nth(2).click();
 await expect(popup.getByRole("heading",{name:"Delivery details",exact:true})).toBeVisible();
 await related("View in dead letters");
 await expect(page.locator("tr.selected-row")).toHaveCount(1);
 await page.locator("tbody tr td").nth(1).click();
 await expect(popup.getByRole("heading",{name:"Dead letter details",exact:true})).toBeVisible();
 await page.screenshot({path:testInfo.outputPath("dead-letter-related-dropdown.png"),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:testInfo.outputPath("tracking-mobile.png"),fullPage:true});
 await popup.getByRole("button",{name:"Close dialog",exact:true}).click();
 await expect(popup).toHaveCount(0);
 await page.setViewportSize({width:1280,height:900});
 await page.getByRole("navigation",{name:"Main navigation"}).getByRole("link",{name:"Overview",exact:true}).click();
 await expect(page.locator(".stat-success strong")).toHaveText("1");await expect(page.locator(".stat-danger strong")).toHaveText("1");
 await expect(page.getByRole("img",{name:/1 successful, 0 pending, 1 awaiting replay/})).toBeVisible();
 await page.screenshot({path:testInfo.outputPath("overview-status-colors.png"),fullPage:true});
 await page.getByRole("button",{name:"Switch to dark theme",exact:true}).click();await page.screenshot({path:testInfo.outputPath("overview-dark.png"),fullPage:true});
 await page.getByRole("navigation",{name:"Main navigation"}).getByRole("link",{name:"Event types",exact:true}).click();
 await page.getByRole("button",{name:"Edit",exact:true}).click();
 const editor=page.locator(".resource-editor");expect((await editor.boundingBox())!.width).toBeGreaterThan(800);
 await expect(editor.locator(".editor-card")).toHaveCount(1);await expect(editor.locator(".danger-zone")).toBeVisible();
 await page.screenshot({path:testInfo.outputPath("edit-card-sections.png"),fullPage:true});
 await editor.getByRole("button",{name:"Close dialog",exact:true}).click();await expect(editor).toHaveCount(0);
 await page.getByRole("navigation",{name:"Main navigation"}).getByRole("link",{name:"Endpoints",exact:true}).click();
 await page.getByRole("row").filter({hasText:"Success destination"}).getByRole("button",{name:"Edit",exact:true}).click();
 await expect(editor.getByRole("button",{name:"Versions",exact:true})).toHaveCount(0);
 await editor.getByLabel("Destination URL",{exact:true}).fill(receiver+"/tracking-edited");
 await editor.getByRole("button",{name:"Save destination",exact:true}).click();await expect(editor).toHaveCount(0);
 await expect(page.getByRole("row").filter({hasText:"Success destination"})).toContainText("/tracking-edited");
 await page.getByRole("row").filter({hasText:"Success destination"}).getByRole("button",{name:"Edit",exact:true}).click();
 await editor.getByRole("button",{name:"Save event mappings",exact:true}).click();await expect(editor).toHaveCount(0);

});
