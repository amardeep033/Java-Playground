package com.example.otel.config;

import io.opentelemetry.api.trace.Span;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.slf4j.MDC;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;
import java.io.IOException;
import java.util.Map;
import java.util.UUID;

// curl -i http://localhost:8080/order \
//   -H 'X-Correlation-ID: checkout-123' \
//   -H 'traceparent: 00-1234567890abcdef1234567890abcdef-1234567890abcdef-01'
// traceparent: version - trace ID - caller's span ID - trace flags; optional because this may be the first request in the chain.

@Component
public class RequestIdsFilter extends OncePerRequestFilter { // OncePerRequestFilter: filter before chain.doFilter -> downstream logic -> same filter's finally block -> response; once per request within a dispatch, with async/error dispatch rules.
    @Override
    protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain chain) throws ServletException, IOException {
        // MDC is a thread-local map with Logback, so we save the previous values and restore them after the request is processed.
        Map<String, String> previous = MDC.getCopyOfContextMap();

        // 1. requestId: unique ID for each request received by this service, generated by us.
        String requestId = UUID.randomUUID().toString();

        // 2. correlationId: ID linking related requests/events across microservices, supplied by the client or generated by us; a flat grouping ID that can coexist with tracing.
        String correlationId = request.getHeader("X-Correlation-ID");
        if (correlationId == null || !correlationId.matches("[A-Za-z0-9._-]{1,64}")) {
            correlationId = UUID.randomUUID().toString();
        }

        // 3. traceId: ID for a distributed trace, created or continued from traceparent by the OpenTelemetry starter; parent/child spans form the hierarchy.
        String traceId = Span.current().getSpanContext().getTraceId();

        try {
            // Put the IDs in MDC for logging.
            MDC.put("requestId", requestId);
            MDC.put("correlationId", correlationId);
            MDC.put("traceId", traceId);

            // Set response headers for client diagnostics; the correlation ID can be reused in related requests, while trace propagation uses traceparent.
            response.setHeader("X-Request-ID", requestId);
            response.setHeader("X-Correlation-ID", correlationId);
            response.setHeader("X-Trace-ID", traceId);

            // Use the existing current OpenTelemetry span and set requestId and correlationId as attributes; this does not create a new span.
            Span.current().setAttribute("request.id", requestId);
            Span.current().setAttribute("correlation.id", correlationId);
            chain.doFilter(request, response);
        } finally {
            // Servlet threads are reused (this request flow is synchronous). Never leak one request's IDs into the next.
            // In Rust's Actix Web, request handling is async; thread-local context still needs care.
            if (previous == null) MDC.clear();
            else MDC.setContextMap(previous);
        }
    }
}

// The important difference is that thread reuse and async task interleaving are separate concerns.
// In Rust (Actix Web), a worker thread can execute multiple requests concurrently by interleaving their async tasks.
// Each async task/future maintains its own local variables. Variables needed across suspension are preserved in the future's state when it suspends at .await and resumes later. This is an async execution property, not tracing context propagation.
// Rust's `tracing` provides async-aware span instrumentation, such as Instrument::instrument, when explicitly applied. It does not automatically propagate context to every spawned task or preserve ordinary local variables.
// Therefore:
// 1. Local variables → belong to a particular async function invocation/future, not inherently to an HTTP request.
// 2. Thread-local variables → belong to the worker thread.
// 3. tracing span context → follows instrumented async execution.

// In Java Servlet (Spring Boot), requests are typically handled by a pool of reusable servlet threads.
// In this synchronous flow, a worker thread executes a request and then becomes available to handle another; async dispatch and virtual-thread configurations can differ.
// Unlike Rust async futures, ordinary servlet request execution is typically synchronous and does not preserve a separate future state per request.
// Therefore:
// 1. Local variables → belong to the method invocation. Separate invocations have separate variables, but referenced objects may still be shared.
// 2. Thread-local variables → belong to the servlet worker thread. They can leak from one request to another if not cleaned up.
// 3. MDC → uses thread-local storage with Logback here. Request IDs placed in MDC must be removed or the previous context restored when request processing finishes.
// 4. Async Servlet processing → may switch threads. MDC and OTel context then need appropriate propagation, through instrumentation or explicit handling.

// Rust vs Servlet: the key distinction
// Concept	Rust Actix	Java Servlet
// Request execution	Async future	Usually synchronous method execution
// Local variables	Values needed across suspension are stored in future state	Belong to the method invocation/frame
// Thread reuse	Yes	Yes
// Thread-local context	Shared by tasks on same thread	Shared by requests on same thread
// Context cleanup	No MDC-style restoration for ordinary locals	No MDC-style restoration for ordinary locals
// Tracing/MDC context	Async-aware span instrumentation; thread-local data still needs care	MDC cleanup/restoration; async context propagation when needed
// The important similarity: In both Rust and Java, local variables belong to their invocation/future; referenced shared state is not automatically request-isolated.
// The important distinction: Logback MDC is thread-local, not request-local. That is why this Servlet filter explicitly restores or clears it.
