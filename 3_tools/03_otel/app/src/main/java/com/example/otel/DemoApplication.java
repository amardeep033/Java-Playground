package com.example.otel;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;

// 1. spring-boot-starter-actuator - for Actuator, which handles health checks and exposes operational endpoints.
// 2. micrometer-registry-prometheus - for exposing Micrometer metrics in Prometheus format; it does not install a Prometheus server.
// 3. opentelemetry-spring-boot-starter - for OpenTelemetry instrumentation and export; this demo uses it for logs and traces.
// Note: Actuator (part of Spring Boot) provides endpoints such as health/metrics/env/info; HTTP exposure is configurable. Micrometer supports backends such as Prometheus and Datadog.
// Micrometer (independent of Prometheus) instruments and records metrics; the Prometheus registry formats them, and a separate Prometheus server can scrape, store, and query them.
// OpenTelemetry supports metrics too. It provides standards, APIs, SDKs, and tools for generating, collecting, and exporting telemetry; Prometheus collects, stores, and queries metrics.

@SpringBootApplication
public class DemoApplication {
    public static void main(String[] args) {
        SpringApplication.run(DemoApplication.class, args);
    }
}

/*
 * Monitoring and Observability (related concepts, not a strict hierarchy)
 * |
 * +-- 1. Monitoring
 * |   +-- Health checks
 * |   +-- Alerts
 * |   +-- Dashboards
 * |
 * +-- 2. Observability
 *     |
 *     +-- IDs for correlation
 *     |   +-- Request ID (requestId): Identifies an individual request; generated by us for each received request
 *     |   +-- Trace ID   (traceId): Identifies a distributed trace; created or continued by OpenTelemetry
 *     |   +-- Correlation ID (correlationId): Links related events/requests; read from the incoming header or generated when missing/invalid, and can be propagated across services
 *     |
 *     +-- Logs
 *     |   +-- Structured logging (JSON)
 *     |   +-- Log levels (INFO, WARN, ERROR, DEBUG)
 *     |   +-- Include requestId, traceId, correlationId where applicable
 *     |
 *     +-- Metrics
 *     |   +-- Counter   : Counts events (use low-cardinality labels)
 *     |   +-- Histogram : Measures distributions (e.g., request latency)
 *     |   +-- Percentiles: p50, p95, p99 (estimated locally or from histogram buckets; this demo publishes local p50/p95 and separate buckets)
 *     |   +-- Avoid high-cardinality labels (e.g., requestId, userId)
 *     |
 *     +-- Traces
 *         +-- Trace : Recorded operations in an execution, potentially spanning multiple services
 *         +-- Spans : Individual operations within a trace
 *         +-- Span context: traceId, spanId, trace flags, trace state, and remote flag; parentSpanId is recorded separately on span data
 */

